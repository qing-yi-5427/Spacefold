// Embedded production UI: scan a new QA source, verify its result, capture the view.
import {chromium,expect} from '@playwright/test';
import {mkdirSync,writeFileSync} from 'node:fs';
import path from 'node:path';
import assert from 'node:assert/strict';
const out=path.resolve(process.env.QA_OUTPUT_DIRECTORY||'artifacts/native-runtime-smoke');
mkdirSync(out,{recursive:true});
const browser=await chromium.connectOverCDP(`http://127.0.0.1:${process.env.QA_CDP_PORT||9232}`);
const page=browser.contexts()[0].pages().find(p=>!p.url().startsWith('devtools:'));
assert.equal(new URL(page.url()).hostname,'tauri.localhost');
assert(!new URL(page.url()).searchParams.has('fixture'));
await page.waitForFunction(()=>window.spacefoldPreview);
await page.getByRole('button',{name:'选择扫描位置',exact:true}).click();
const source=path.resolve('artifacts/native-ui-source');
await page.locator('[data-scan-path]').fill(source);
const previousScanId=await page.evaluate(()=>window.spacefoldPreview.getScan()?.scanId);
await page.getByRole('button',{name:'开始扫描',exact:true}).click();
await expect.poll(()=>page.evaluate(({source,previousScanId})=>{
  const scan=window.spacefoldPreview.getScan();
  return scan?.source===source&&scan.scanId!==previousScanId&&scan.status==='completed';
},{source,previousScanId})).toBe(true);
const scan=await page.evaluate(()=>window.spacefoldPreview.getScan());
assert.equal(scan.source,source);
assert.equal(scan.discoveredCount,'501');
assert.equal(scan.logicalTotalBytes,'128000');
assert.equal(scan.errorCount,'0');
assert(!scan.incomplete);
await page.locator('[data-sf-view="tree"]').click();
await expect(page.locator('[data-wb-row]').first()).toBeVisible();
const screenshot=path.join(out,'actual-embedded-webview.png');
await page.screenshot({path:screenshot,scale:'css'});
const result={passed:true,url:page.url(),actualProductionWebview:true,fixtureMode:false,engine:await browser.version(),scan,screenshot};
writeFileSync(path.join(out,'results.json'),JSON.stringify(result,null,2));
console.log(JSON.stringify(result,null,2));
await browser.close();
